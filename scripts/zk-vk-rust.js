// Converts zk/vkey.json (snarkjs) into program/src/vk.rs for groth16-solana.
// G1 = x || y, G2 = x.c1 || x.c0 || y.c1 || y.c0, all 32-byte big-endian.
const fs = require('fs'); const path = require('path');
const vk = JSON.parse(fs.readFileSync(path.join(__dirname, '..', 'zk', 'vkey.json')));
const be = (n) => [...Buffer.from(BigInt(n).toString(16).padStart(64, '0'), 'hex')];
const g1 = (p) => [...be(p[0]), ...be(p[1])];
const g2 = (p) => [...be(p[0][1]), ...be(p[0][0]), ...be(p[1][1]), ...be(p[1][0])];
const arr = (b) => '[' + b.join(', ') + ']';
const out = `// Generated by scripts/zk-vk-rust.js from zk/vkey.json. Do not edit.
use groth16_solana::groth16::Groth16Verifyingkey;
pub const NR_INPUTS: usize = ${vk.nPublic};
pub const VERIFYING_KEY: Groth16Verifyingkey = Groth16Verifyingkey {
    nr_pubinputs: ${vk.nPublic},
    vk_alpha_g1: ${arr(g1(vk.vk_alpha_1))},
    vk_beta_g2: ${arr(g2(vk.vk_beta_2))},
    vk_gamme_g2: ${arr(g2(vk.vk_gamma_2))},
    vk_delta_g2: ${arr(g2(vk.vk_delta_2))},
    vk_ic: &[${vk.IC.map((p) => arr(g1(p))).join(',\n        ')}],
};
`;
fs.writeFileSync(path.join(__dirname, '..', 'program', 'src', 'vk.rs'), out); console.log('vk.rs written, inputs', vk.nPublic);
